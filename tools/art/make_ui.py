def canvas(w, h):
    return Image.new("RGBA", (w, h), (0, 0, 0, 0))


def px(im, x, y, c):
    if 0 <= x < im.width and 0 <= y < im.height:
        im.putpixel((x, y), c + (255,) if len(c) == 3 else c)


def rect(im, x0, y0, x1, y1, c):
    for y in range(y0, y1 + 1):
        for x in range(x0, x1 + 1):
            px(im, x, y, c)


def bevel(im, x0, y0, x1, y1, hi, lo, width=1):
    for k in range(width):
        for x in range(x0 + k, x1 - k + 1):
            px(im, x, y0 + k, hi)
            px(im, x, y1 - k, lo)
        for y in range(y0 + k, y1 - k + 1):
            px(im, x0 + k, y, hi)
            px(im, x1 - k, y, lo)


def outline(im, x0, y0, x1, y1, c, round_corners=True):
    for x in range(x0 + (1 if round_corners else 0), x1 + (0 if round_corners else 1)):
        px(im, x, y0, c)
        px(im, x, y1, c)
    for y in range(y0 + (1 if round_corners else 0), y1 + (0 if round_corners else 1)):
        px(im, x0, y, c)
        px(im, x1, y, c)


def noise(im, x0, y0, x1, y1, base, amount, rng, sparse=1.0):
    for y in range(y0, y1 + 1):
        for x in range(x0, x1 + 1):
            if rng.random() < sparse:
                d = rng.randint(-amount, amount)
                px(im, x, y, tuple(max(0, min(255, c + d)) for c in base))


def board(rng):
    """Oak planks in a walnut frame, with a nail in each corner."""
    im = canvas(48, 48)
    rect(im, 0, 0, 47, 47, WALNUT)
    for y in range(4, 44):
        plank = (y - 4) // 8
        base = OAK if plank % 2 == 0 else (144, 100, 62)
        for x in range(4, 44):
            grain = ((x * 3 + plank * 17) % 23 == 0) or ((x + y * 5 + plank * 7) % 29 == 0)
            px(im, x, y, OAK_LO if grain else base)
        if (y - 4) % 8 == 0:
            for x in range(4, 44):
                px(im, x, y, OAK_HI)
        if (y - 4) % 8 == 7:
            for x in range(4, 44):
                px(im, x, y, OAK_LO)
    bevel(im, 0, 0, 47, 47, WALNUT_HI, WALNUT_LO, 2)
    bevel(im, 3, 3, 44, 44, WALNUT_LO, WALNUT_HI, 1)
    outline(im, 0, 0, 47, 47, INK)
    for nx, ny in ((6, 6), (40, 6), (6, 40), (40, 40)):
        rect(im, nx, ny, nx + 1, ny + 1, GREY)
        px(im, nx, ny, CREAM)
        px(im, nx + 1, ny + 1, GREY_LO)
    return im


def tablet(rng):
    """A wax writing tablet in its wooden frame."""
    im = canvas(48, 48)
    rect(im, 0, 0, 47, 47, WALNUT)
    noise(im, 1, 1, 46, 46, WALNUT, 5, rng, 0.3)
    bevel(im, 1, 1, 46, 46, WALNUT_HI, WALNUT_LO, 2)
    rect(im, 5, 5, 42, 42, WAX)
    noise(im, 5, 5, 42, 42, WAX, 4, rng, 0.25)
    for x in range(5, 43):
        px(im, x, 5, WAX_LO)
    for y in range(5, 43):
        px(im, 5, y, WAX_LO)
    for x in range(5, 43):
        px(im, x, 42, WAX_HI)
    for y in range(5, 43):
        px(im, 42, y, WAX_HI)
    outline(im, 0, 0, 47, 47, INK)
    return im


def page(rng):
    """Parchment in a thin walnut frame with a dark outer line, so a window stands out from what is behind it."""
    im = canvas(48, 48)
    rect(im, 1, 1, 46, 46, PARCH)
    noise(im, 2, 2, 45, 45, PARCH, 5, rng, 0.35)
    bevel(im, 1, 1, 46, 46, WALNUT_HI, WALNUT_LO, 1)
    outline(im, 2, 2, 45, 45, WALNUT_LO, round_corners=False)
    for k, c in enumerate((PARCH_LO, (226, 208, 168))):
        for x in range(3 + k, 45 - k):
            px(im, x, 3 + k, c)
            px(im, x, 44 - k, c)
        for y in range(3 + k, 45 - k):
            px(im, 3 + k, y, c)
            px(im, 44 - k, y, c)
    outline(im, 0, 0, 47, 47, INK)
    return im


def card(rng):
    """A paper notice with a darker edge, slightly shadowed below and to the right."""
    im = canvas(32, 32)
    rect(im, 1, 1, 31, 31, (40, 26, 20, 90))
    rect(im, 0, 0, 30, 30, (246, 238, 214))
    noise(im, 1, 1, 29, 29, (246, 238, 214), 4, rng, 0.3)
    bevel(im, 1, 1, 29, 29, PARCH_HI, PARCH_LO, 1)
    outline(im, 0, 0, 30, 30, WALNUT, round_corners=False)
    return im


def button(fill, hi, lo, edge=INK, pressed=False):
    im = canvas(24, 24)
    rect(im, 1, 1, 22, 22, fill)
    if pressed:
        bevel(im, 1, 1, 22, 22, lo, hi, 1)
    else:
        bevel(im, 1, 1, 22, 22, hi, lo, 1)
        for x in range(2, 22):
            px(im, x, 21, lo)
    outline(im, 0, 0, 23, 23, edge)
    return im


def tab(on):
    im = canvas(24, 16)
    fill = PARCH if on else PARCH_LO
    rect(im, 1, 1, 22, 15, fill)
    bevel(im, 1, 1, 22, 15, PARCH_HI if on else PARCH, PARCH_LO if on else (190, 166, 124), 1)
    for x in range(1, 23):
        px(im, x, 0, PARCH_EDGE)
    for y in range(1, 16):
        px(im, 0, y, PARCH_EDGE)
        px(im, 23, y, PARCH_EDGE)
    if not on:
        for x in range(0, 24):
            px(im, x, 15, PARCH_EDGE)
    return im


def tooltip():
    im = canvas(16, 16)
